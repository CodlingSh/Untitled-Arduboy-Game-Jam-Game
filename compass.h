  private:
    Arduboy2 *ab;
    uint8_t *arrowSpr = arrowUp; 
    
  public:
    Compass(Arduboy2 *ab_ptr) : ab(ab_ptr) {}

    void changeDir(uint8_t dir) {
      switch(dir) {
        case 0:
          arrowSpr = arrowUp;
          break;
        case 1:
          arrowSpr = arrowRight;
          break;
        case 2:
          arrowSpr = arrowDown;
          break;
        case 3:
          arrowSpr = arrowLeft;
          break;
        case 5:
          break;
      }
    }

