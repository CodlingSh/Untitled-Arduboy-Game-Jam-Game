class Title {
  private:
    Arduboy2 *ab;
    int8_t selection = 0;
    bool startSel = true, helpSel = false, creditsSel = false, settingsSel = false;

  public:
    Title(Arduboy2 *ab_ptr) : ab(ab_ptr) {}

    void update() {
      if (ab->justPressed(UP_BUTTON)) {
        selection--;

        if (selection < 0) {
          selection = 3;
        }
      }

      if (ab->justPressed(DOWN_BUTTON)) {
        selection++;

        if (selection >= 4) {
          selection = 0;
        }
      }

      startSel = false;
      helpSel = false;
      settingsSel = false;
      creditsSel = false;

      switch (selection) {
        case 0:
          startSel = true;
          break;
        case 1:
          helpSel = true;
          break;
        case 2:
          settingsSel = true;
          break;
        case 3:
          creditsSel = true;
          break;
      }
    }

    int8_t getSelection() {
      return selection;
    }

    void draw() {
      uint8_t menuY = 1;

      Sprites::drawOverwrite(-11, 4, logo, 0);
      Sprites::drawOverwrite(85, menuY, start, startSel);
      Sprites::drawOverwrite(85, menuY + 16, help, helpSel);
      Sprites::drawOverwrite(85, menuY + 32, settings, settingsSel);
      Sprites::drawOverwrite(85, menuY + 48, credits, creditsSel);
    }
};

