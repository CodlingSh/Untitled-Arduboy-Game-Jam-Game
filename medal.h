class Medal {
  private:
    Arduboy2 *ab;
    uint8_t x = 0;
    uint8_t y = 0;
    uint8_t height = 10;
    uint8_t width = 10;
    uint8_t timer = 42;
    uint8_t localT = 60;
    uint8_t animTimer = 3;
    uint8_t currFrame = 1;

  public:
    Medal(Arduboy2 *ab_ptr) : ab(ab_ptr) {}

    uint8_t setX() {
      uint8_t rnd = random(8) * 8 + 64;
      return rnd;
    }

    uint8_t setY() {
      uint8_t rnd = random(8) * 8;
      return rnd;
    }

    uint8_t getX() {
      return x;
    }

    uint8_t getY() {
      return y;
    }

    uint8_t getWidth() {
      return width;
    }

    uint8_t getHeight() {
      return height;
    }

    void spawn(uint8_t playerX, uint8_t playerY) {
      uint8_t rndX;
      uint8_t rndY;

      rndX = random(52) + 2;
      rndY = random(52) + 2;

      while (abs(rndX - (playerX + 4)) <= 20) {
        rndX = random(52) + 2;
      }

      while ((abs(rndY - (playerY + 4)) <= 20)) {
        rndY = random(52) + 2;
      }

      x = rndX;
      y = rndY;
      timer = 42;
      localT = 60;
    }

    uint8_t getTimerScore() { 
      return ((uint16_t)timer * 49 + 21) / 42 + 1; 
    }

    void animate() {
      animTimer--;

      if (animTimer == 0) {
        currFrame++;

        if (currFrame > 7) {
          currFrame = 0;
        }

        animTimer = 3;
      }
    }

    void update() {
      // Decrease timer
      if (timer != 0) {localT--;}
      
      if (localT == 0) {
        if (timer != 0) {
          timer--;
          localT = 3;
        }
      }

      animate();
    }

    void draw() {
      Sprites::drawExternalMask(x, y, star, starMask, currFrame, 0);
      // ab->print("X: ");
      // ab->println(x);
      // ab->println(localT);
      // ab->println(timer);
      
      // Draw timer bar
      ab->fillRect(65, 44 - timer, 4, 0 + timer);
    }
};

