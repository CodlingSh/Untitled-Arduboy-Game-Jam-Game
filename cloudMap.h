class CloudMap {
  private:
    Compass *compass;
    double xOffset = 0;
    double yOffset = 0;
    int16_t lastX = 0;
    int16_t lastY = 0;
    int8_t dx = 0;
    int8_t dy = 0;
    float speed = 0.25;
    bool windBlowing = false;
    uint8_t windDirection = 5; // 0 = N, 1 = E, 2 = S, 3 = W, 5 = none
    uint8_t secondTimer = 60;
    uint8_t windTimer = 0;
  public:
    CloudMap(Compass *com_ptr) : compass(com_ptr) {}

    void update() {
        lastX = (int16_t)xOffset;
        lastY = (int16_t)yOffset;

      if (windBlowing == false) {
        secondTimer--;

        if (secondTimer == 0) {
          windBlowing = true;
          windTimer = 2;//random(2, 5);
          secondTimer = 60;
        }
      }

      if (windBlowing == true && windDirection == 5) {
        windDirection = 0;//random(4);
        compass->changeDir(windDirection);
      }        

      switch(windDirection) {
        case 0: // North
          yOffset += speed;
          break;
        case 1: // East
          xOffset -= speed;
          break;
        case 2: // South
          yOffset -= speed;
          break;
        case 3: // West
          xOffset += speed;
      }

      if (windBlowing == true) {
        secondTimer--;

        if (secondTimer == 0) {
          windTimer--;
          secondTimer = 60;
        }

        if (windTimer == 0) {
          windBlowing = false;
          windDirection = 5;
        }
      }

      // Stop clouds from scrolling out of bounds
      if (xOffset < 0) xOffset = 0;
      if (yOffset < 0) yOffset = 0;
      if (xOffset > 448) xOffset = 448;
      if (yOffset > 448) yOffset = 448;

      dx = (int16_t)xOffset - lastX;
      dy = (int16_t)yOffset - lastY;
    }

    bool cloudCollide(uint8_t playerX, uint8_t playerY) {
      uint8_t mapPixelX = playerX + (int8_t)xOffset;
      uint8_t mapPixelY = playerY + (int8_t)yOffset;
      
      // Top-left
      uint8_t gridX = mapPixelX / 8;
      uint8_t gridY = mapPixelY / 8;
      if (((map1[gridY] >> (63 - gridX)) & 1ULL)) return true;

      // Top-right
      gridX = (mapPixelX + 7) / 8;
      gridY = mapPixelY / 8;
      if (((map1[gridY] >> (63 - gridX)) & 1ULL)) return true;

      // Bottom-left
      gridX = mapPixelX / 8;
      gridY = (mapPixelY + 7) / 8;
      if (((map1[gridY] >> (63 - gridX)) & 1ULL)) return true;

      // Bottom-right
      gridX = (mapPixelX + 7) / 8;
      gridY = (mapPixelY + 7) / 8;
      if (((map1[gridY] >> (63 - gridX)) & 1ULL)) return true;

      return false;
    }


    void draw() {
      int16_t xOff = (int16_t)xOffset;
      int16_t yOff = (int16_t)yOffset;

      int16_t xStart = xOff >> 3;
      int16_t yStart = yOff >> 3;

      int16_t xEnd = xStart + 9; // 8 visible tiles + 1 partial tile
      int16_t yEnd = yStart + 9;

      for (uint8_t y = yStart; y < yEnd; y++) {
        for (uint8_t x = xStart; x < xEnd; x++) {
          if (map1[y] >> (63 - x) & 1ULL) {
            Arduboy2Base::drawBitmap(x * 8 - xOff, y * 8 - yOff, cloud, 8, 8, WHITE);
          }
        }
      }
    }

    uint16_t getMap() {
      return map1;
    }
};

